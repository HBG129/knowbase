export const translations: Record<Lang, Readonly<Record<TranslationKey, string>>> = {
  zh: zhTranslations,
  en: enTranslations,
};

export function t(lang: Lang, key: TranslationKey, values?: TranslationValues): string {
  const table = translations[lang] ?? translations.zh;
  const template = table[key] ?? translations.zh[key] ?? key;
  if (!values) return template;

  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (placeholder, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : placeholder
  );
}
